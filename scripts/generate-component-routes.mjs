#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const webDir = path.join(root, "apps/web");
const docsDir = path.join(webDir, "components/docs");
const lazyRegistryPath = path.join(webDir, "components/docs/lazy-registry.ts");
const registryPath = path.join(webDir, "public/r/registry.json");
const hiddenPath = path.join(webDir, "lib/hidden-components.ts");

const MARKER = "// @generated by scripts/generate-component-routes.mjs — do not edit.";
const SLUG_RE = /^[a-z0-9][a-z0-9-]*$/;
const IDENTIFIER_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function fail(message) {
  console.error(`[generate-component-routes] ${message}`);
  process.exit(1);
}

function parseDocsMap() {
  if (!fs.existsSync(lazyRegistryPath)) {
    fail(`missing ${path.relative(root, lazyRegistryPath)}`);
  }

  const source = fs.readFileSync(lazyRegistryPath, "utf8");
  const entryRe =
    /^\s*(?:"([^"]+)"|([A-Za-z0-9_$]+)):\s*\(\)\s*=>\s*import\("@\/components\/docs\/([^"]+)"\)\.then\(\(m\)\s*=>\s*\(\{\s*default:\s*m\.([A-Za-z0-9_$]+),?\s*\}\)\)/gm;
  const entries = [...source.matchAll(entryRe)].map(([, quotedSlug, bareSlug, modulePath, exportName]) => ({
    slug: quotedSlug ?? bareSlug,
    modulePath,
    exportName,
  }));

  const keys = [...source.matchAll(/^\s*(?:"([^"]+)"|([A-Za-z0-9_$]+)):\s*\(\)\s*=>/gm)].map(
    ([, quotedSlug, bareSlug]) => quotedSlug ?? bareSlug,
  );

  if (entries.length !== keys.length) {
    fail(
      `parsed ${entries.length} docs imports but found ${keys.length} map keys; update the parser before continuing`,
    );
  }

  const seen = new Set();
  for (const entry of entries) {
    if (seen.has(entry.slug)) fail(`duplicate docs slug: ${entry.slug}`);
    seen.add(entry.slug);

    if (!SLUG_RE.test(entry.slug)) fail(`invalid slug: ${entry.slug}`);
    if (!IDENTIFIER_RE.test(entry.exportName)) fail(`invalid export name for ${entry.slug}: ${entry.exportName}`);

    const moduleFile = path.join(docsDir, `${entry.modulePath}.tsx`);
    if (!fs.existsSync(moduleFile)) {
      fail(`missing docs module for ${entry.slug}: ${path.relative(root, moduleFile)}`);
    }

    const moduleSource = fs.readFileSync(moduleFile, "utf8");
    const declarationRe = new RegExp(
      `export\\s+(?:async\\s+)?(?:function|const|class)\\s+${entry.exportName}\\b`,
    );
    const namedExportRe = new RegExp(`export\\s*\\{[^}]*\\b${entry.exportName}\\b[^}]*\\}`);
    if (!declarationRe.test(moduleSource) && !namedExportRe.test(moduleSource)) {
      fail(`docs module ${entry.modulePath} does not export ${entry.exportName}`);
    }
  }

  return entries;
}

function parseHiddenSlugs() {
  const source = fs.readFileSync(hiddenPath, "utf8");
  const setMatch = source.match(/new Set<string>\(\[(.*?)\]\)/s);
  if (!setMatch) fail(`could not find HIDDEN_COMPONENT_SLUGS in ${path.relative(root, hiddenPath)}`);
  return new Set([...setMatch[1].matchAll(/"([^"]+)"/g)].map(([, slug]) => slug));
}

function parseRegistrySlugs() {
  const registry = JSON.parse(fs.readFileSync(registryPath, "utf8"));
  if (!Array.isArray(registry.items)) fail("registry.json is missing an items array");
  return new Set(registry.items.map((item) => item.name).filter(Boolean));
}

function cleanGeneratedRoutes(baseDir) {
  if (!fs.existsSync(baseDir)) return;
  for (const name of fs.readdirSync(baseDir)) {
    const dir = path.join(baseDir, name);
    if (!fs.statSync(dir).isDirectory()) continue;
    const page = path.join(dir, "page.tsx");
    if (!fs.existsSync(page)) continue;
    if (fs.readFileSync(page, "utf8").startsWith(MARKER)) {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }
}

function writeRoute(baseDir, slug, source) {
  const dir = path.join(baseDir, slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "page.tsx"), source);
}

const docsEntries = parseDocsMap();
const hiddenSlugs = parseHiddenSlugs();
const registrySlugs = parseRegistrySlugs();

for (const entry of docsEntries) {
  if (!registrySlugs.has(entry.slug)) {
    fail(`docs slug ${entry.slug} is not present in public/r/registry.json`);
  }
}

const generatedEntries = docsEntries.filter((entry) => !hiddenSlugs.has(entry.slug));
const docsBase = path.join(webDir, "app/docs/components");
const experienceBase = path.join(webDir, "app/experience/components");
const docsSlugsPath = path.join(webDir, "lib/docs-slugs.generated.ts");

fs.writeFileSync(
  docsSlugsPath,
  `${MARKER}
export const DOCS_SLUGS = [
${generatedEntries.map((entry) => `  "${entry.slug}",`).join("\n")}
] as const;
`,
);

cleanGeneratedRoutes(docsBase);
cleanGeneratedRoutes(experienceBase);

for (const { slug, modulePath, exportName } of generatedEntries) {
  const importPath = `@/components/docs/${modulePath}`;

  writeRoute(
    docsBase,
    slug,
    `${MARKER}
import { ${exportName} } from "${importPath}";
import { DocsComponentPage, docsMetadata } from "@/components/docs-component-page";

export const metadata = docsMetadata("${slug}");

export default function Page() {
    return <DocsComponentPage slug="${slug}" DocsComponent={${exportName}} />;
}
`,
  );

  writeRoute(
    experienceBase,
    slug,
    `${MARKER}
import { ${exportName} } from "${importPath}";
import { ExperienceComponentPage, experienceMetadata } from "@/components/experience-component-page";

export const metadata = experienceMetadata("${slug}");

export default function Page() {
    return <ExperienceComponentPage slug="${slug}" DocsComponent={${exportName}} />;
}
`,
  );
}

const skipped = docsEntries.length - generatedEntries.length;
console.log(
  `[generate-component-routes] generated ${generatedEntries.length} docs + ${generatedEntries.length} experience routes` +
    (skipped > 0 ? ` (skipped ${skipped} hidden)` : ""),
);
